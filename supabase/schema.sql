-- =========================================================
-- COOPERATIVA AGRÍCOLA - ESQUEMA PARA SUPABASE
-- Ejecutar completo desde Supabase > SQL Editor > New query.
-- =========================================================

begin;

create table if not exists public.tramites (
    id bigint generated by default as identity primary key,
    proveedor text not null,
    matricula text not null,
    fecha date not null,
    hora time without time zone not null,
    direccion text not null,
    producto text not null,
    unidad_medida text not null,
    creado_en timestamptz not null default now()
);

-- Activar seguridad a nivel de fila.
alter table public.tramites enable row level security;

-- Solo usuarios autenticados pueden usar esta tabla.
revoke all on table public.tramites from anon;
revoke all on sequence public.tramites_id_seq from anon;
grant usage on schema public to authenticated;
grant select, insert, update, delete on table public.tramites to authenticated;
grant usage, select on sequence public.tramites_id_seq to authenticated;

-- Política de lectura: cualquier usuario que haya iniciado sesión
-- puede consultar los trámites de la cooperativa.
drop policy if exists "Usuarios autenticados pueden consultar tramites" on public.tramites;
create policy "Usuarios autenticados pueden consultar tramites"
on public.tramites
for select
to authenticated
using (true);

-- Política de inserción.
drop policy if exists "Usuarios autenticados pueden registrar tramites" on public.tramites;
create policy "Usuarios autenticados pueden registrar tramites"
on public.tramites
for insert
to authenticated
with check (true);

-- Política de actualización.
drop policy if exists "Usuarios autenticados pueden actualizar tramites" on public.tramites;
create policy "Usuarios autenticados pueden actualizar tramites"
on public.tramites
for update
to authenticated
using (true)
with check (true);

-- Política de eliminación.
drop policy if exists "Usuarios autenticados pueden eliminar tramites" on public.tramites;
create policy "Usuarios autenticados pueden eliminar tramites"
on public.tramites
for delete
to authenticated
using (true);

-- La autenticación de usuarios la administra Supabase Auth.
-- No se almacena ninguna contraseña en la tabla tramites.

commit;
